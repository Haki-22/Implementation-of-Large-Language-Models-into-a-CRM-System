"""SQLModel entities for the shared substrate CRM database.

The substrate has two surfaces and the split decides what is a table here.

**CRM content (this file, persisted in ``substrate.db``)** -- everything a CRM
record actually consists of and that a user or an LLM tool could ask about at
run time: :class:`Contact`, :class:`Note`, :class:`Company`, :class:`Product`,
:class:`Order`, :class:`Review` and :class:`MessageBrief`. UC-03 reads contacts
and notes through its MCP tools and appends notes; the frontend bridge reads
contacts, briefs and the purchase history. The customer's own words -- the
review behind each order, in the English original and the Czech translation --
are CRM content too (decision D-DB-3, 2026-09-04): they are what UC-01 mirrors,
UC-04 mines and UC-03 searches, so they live in :class:`Review` with a full-text
index rather than in JSON files every use case re-parses.

**Derived customer attributes (also here).** What a CRM computes or receives
about a customer and then shows on the record: the lifecycle stage
(:class:`LifecycleStage` vocabulary + ``Contact.lifecycle_stage``, arithmetic
over the orders at build time) and what the recommender produced for the
person -- :class:`Recommendation`, :class:`Topic`, :class:`Aspect`. The latter
three are loaded by the database build from UC-04's committed result files,
exactly as the inferred OCEAN profiles are (decision 2026-09-04: UC-04 runs
first, its results are snapshots, the database carries them, UC-01 reads only
the database). They are empty until UC-04 has produced them, never fabricated.

**Experiment bookkeeping (deliberately not here)** -- generated messages, error
rows, evaluation records and judge fixtures live in committed JSON and CSV next
to the run that produced them, so every number in the thesis reproduces without
this git-ignored database. UC-02's PII answer key (planted messages + gold
spans) is likewise a snapshot artifact, regenerated from contact rows.
"""

