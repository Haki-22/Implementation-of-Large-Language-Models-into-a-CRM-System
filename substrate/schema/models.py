class ChangeLog(SQLModel, table=True):
    """
    One field change requested through UC-03's MCP server.

    Written for every ``update_contact`` / ``update_company`` call. Under the
    ``strict`` security profile the change is recorded but **not applied**
    (``applied = False``) until a person reviews it (``review.py``); under
    ``open`` and ``masked`` it is applied at once and the row is the record of
    what the model changed. Every change names the ``updated_at`` the model read
    (``entity_updated_at``); the server refuses a stale one and a held change is
    applied only while the entity still carries that timestamp. The timestamp
    moves on every write, so it is the only guard needed. ``old_value`` / ``new_value`` are stored as text so
    a reviewer can read them without knowing the column type.
    """

    __tablename__ = "uc_change_log"

    id: Optional[int] = Field(default=None, primary_key=True)
    entity_type: str = Field(..., description="'contact' or 'company'.")
    entity_id: int = Field(..., index=True)
    field: str = Field(..., description="Column name that was (or is to be) changed.")
    old_value: Optional[str] = Field(default=None)
    new_value: Optional[str] = Field(default=None)
    author: str = Field(..., description="'human' or 'llm:<model>'.")
    audit_seq: Optional[int] = Field(default=None)
    created_at: datetime = Field(default_factory=datetime.utcnow)
    entity_updated_at: Optional[datetime] = Field(
        default=None,
        description=(
            "The entity's updated_at the model read and passed back; a held change is applied "
            "only while the entity still carries it (optimistic concurrency by timestamp)."
        ),
    )
    applied: bool = Field(default=False, description="True once the value is on the row.")
    reviewed_at: Optional[datetime] = Field(default=None)
    review_outcome: Optional[str] = Field(
        default=None,
        description="'applied', 'rejected', or 'conflict' (the field moved before the review).",
    )


class LifecycleStage(SQLModel, table=True):
    """
    The customer lifecycle vocabulary: one row per stage code.

    Seven rows seeded at build from ``substrate.constants.LIFECYCLE_STAGES``:
    six RFM stages (Berry & Linoff ch. 5, Kumar & Reinartz section 6.1) plus
    ``prospect`` for a contact that never bought. Keyed by the code so a query
    stays readable (``WHERE lifecycle_stage = 'churned'``); the Czech and English
    labels live here, once, and a prompt or a screen joins them. ``rule`` states
    the threshold in words for a reader of the database.
    """

    __tablename__ = "uc_lifecycle_stages"

    code: str = Field(primary_key=True, description="Stage code, e.g. 'loyal_active'")
    label_cs: str = Field(
        ..., description="Czech label a prompt pastes, e.g. 'dlouhodobě věrný zákazník'"
    )
    label_en: str = Field(..., description="English label")
    rule: str = Field(..., description="The threshold that assigns the stage, in words")


